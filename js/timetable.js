// Moodle page for a session: lectures use the course page, exercises the exercise page if it has its own
function moodleUrl(courseId, type) {
  const course = COURSES.find(c => c.id === courseId);
  if (!course) return null;
  const isLecture = type === 'L' || type === 'VI';
  return (!isLecture && course.moodleExercise) || course.moodle || null;
}

// Helper to convert "HH:MM" to minutes from 00:00
function timeToMinutes(t) {
  const parts = t.split(':').map(Number);
  return parts[0] * 60 + parts[1];
}

